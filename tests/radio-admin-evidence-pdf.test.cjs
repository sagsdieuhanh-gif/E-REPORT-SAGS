'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const c=fs.readFileSync('app/modules/radio-custody.v1.js','utf8');
const rules=fs.readFileSync('firebase/radio-custody.rules.snippet','utf8');
assert(c.includes('id="radioPdfIncludePhotos"'),'Include-photo choice missing');
assert(c.includes("$('radioPdfChoice').hidden=!isAdmin(currentUser())||t==='devices'"),'Only AD should see photo option');
assert(c.includes("if($('radioPdfIncludePhotos')?.checked&&isAdmin(currentUser()))return exportPhotoPdf()"),'PDF checkbox must control export');
assert(c.includes("if(!isAdmin(currentUser()))return notify('Chỉ tài khoản AD"),'PDF operation must check permissions again');
assert(c.includes('historyVerified=!s.metadata.fromCache&&navigator.onLine'),'photos require server-verified history');
assert(!c.includes("if(rows.length>16)"),'do not silently omit evidence');
assert(c.includes('stored.push(pdfStoredPage(await photoPdfPage('),'every filtered event must produce image appendix page');
assert(c.includes('async function photoPdfPage('),'photo PDF canvas missing');
assert(c.includes('x.drawImage(img,'),'actual image must be embedded in evidence PDF');
assert(c.includes('const blob=pdfBuild(stored)'),'photo pages must use binary PDF builder');
assert(c.includes('const check=photoAudit(e)'),'in-app photo viewer must compare timestamps');
assert(c.includes('details:evidenceDetails(details,photos.old?.at)'));
assert(c.includes('details:evidenceDetails(details,photos.new?.at)'));
assert(rules.includes("d.keys().hasOnly(['schemaVersion','action'"),'existing immutable schema expected');
const start=c.indexOf('function evidenceDetails('),stop=c.indexOf('function eventData(',start);
assert(start>=0&&stop>start);
const ctx={S:x=>String(x??'').trim(),Date,Math,Number};
vm.createContext(ctx);
vm.runInContext(c.slice(start,stop)+'\nthis.photoAudit=photoAudit;this.evidenceDetails=evidenceDetails;',ctx);
const at=Date.parse('2026-11-03T03:01:09.000Z');
const note=ctx.evidenceDetails('Lý do trả: Hết ca',at);
assert(note.includes('Ảnh thiết bị UTC: 2026-11-03T03:01:09.000Z'));
assert(note.length<=500);
const a=ctx.photoAudit({details:note,at:{toMillis:()=>at+50000}});
assert.equal(a.delta,1);
assert.match(a.status,/GẦN GIỜ/);
const b=ctx.photoAudit({details:note,at:{toMillis:()=>at+60*60000}});
assert(b.delta>=59);
assert.match(b.status,/CẢNH BÁO/);
const prior=ctx.photoAudit({details:'old no metadata',at:{toMillis:()=>at}});
assert.match(prior.status,/ẢNH CŨ/);
console.log('AD radio evidence export: image, role gate, verified Firebase time, historical audits PASS');
