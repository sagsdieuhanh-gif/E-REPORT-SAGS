'use strict';
const fs=require('fs'),assert=require('node:assert/strict'),crypto=require('node:crypto');
const html=fs.readFileSync('index.html','utf8');
const version=JSON.parse(fs.readFileSync('version.json','utf8'));
const manifest=JSON.parse(fs.readFileSync('asset-manifest.json','utf8'));
assert.equal(version.version,'V1.10');
assert(!html.includes('id="sagsCanonicalProduction"'),'GitHub Pages must not redirect to blocked Vercel');
assert(!html.includes('location.replace(u.href)'),'No legacy canonical redirect');
assert(html.includes('./manifest.webmanifest') && html.includes('./app/generated/runtime-4.js'),'GitHub Pages assets remain relative to application root');
assert(fs.existsSync('forms/forms.registry.json'),'Published PDF registry must exist');
const reg=JSON.parse(fs.readFileSync('forms/forms.registry.json','utf8'));
assert.equal(reg.schema,2);
assert(Array.isArray(reg.forms)&&reg.forms.length>0);
const bytes=fs.readFileSync('index.html');
assert.equal(manifest.assets['./index.html'].sha256,crypto.createHash('sha256').update(bytes).digest('hex'));
assert.equal(manifest.assets['./index.html'].bytes,bytes.length);
console.log('GitHub Pages V1.10: standalone routing, registry and pinned asset hash OK');
