const fs=require('node:fs'),assert=require('node:assert/strict');
const html=fs.readFileSync(__dirname+'/../index.html','utf8'),repair=fs.readFileSync(__dirname+'/../repair.html','utf8');
assert.doesNotMatch(html,/id="sagsCanonicalProduction"/);
assert.doesNotMatch(html,/__SAGS_TEST_DEPLOYMENT=true|id="sagsTestResetGate"/);
assert.match(repair,/startsWith\('sags-'\)/);
assert.match(repair,/startsWith\('e-report-'\)/);
assert.match(repair,/\.\/index\.html/);
assert.match(repair,/__repair/);
assert.doesNotMatch(repair,/localStorage\.clear\(|indexedDB\.deleteDatabase\(/);
console.log('GitHub Pages stays on this host and repair preserves drafts');
