'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const css=fs.readFileSync('app/styles/aviation-reference.v1.css','utf8');
const index=fs.readFileSync('index.html','utf8');
const version=JSON.parse(fs.readFileSync('version.json','utf8'));
const manifest=JSON.parse(fs.readFileSync('asset-manifest.json','utf8'));
const sw=fs.readFileSync('service-worker.js','utf8');
assert.match(version.version,/^V1\.\d+(?:\.\d+)?$/,'Keep V1.x display version series');
assert.equal(version.displayVersion,version.version,'Display version must match release version');
assert.equal(manifest.version,version.version);
assert.equal(manifest.build,version.build);
assert.equal(sw.match(/const DISPLAY_VERSION='([^']+)'/)[1],version.version);
assert.equal(sw.match(/const BUILD='([^']+)'/)[1],version.build);
assert(index.includes('aviation-reference.v1.css?v='+version.build),'Aviation stylesheet cache-busted with current build');
const start=css.indexOf('/* V1.0 home-screen readability adjustment, PC first.');
assert(start>0,'Dedicated readability layer missing');
const layer=css.slice(start);
assert.match(layer,/@media screen and \(min-width:901px\)/,'PC-only readability CSS');
assert.match(layer,/@media screen and \(max-width:900px\)/,'Mobile-only typography CSS');
for(const selector of ['.v6494Nav button span b','.v6494Nav button span small','.v6494Nav h3','.v6494Profile b','.v6494TopIdentity b','.opsAirlineIdentity small','.opsMetricLabel','.opsMetricCta','.opsQueueHead h2','#opsHomeFlights th'])assert(layer.includes(selector),'missing visible screen typography: '+selector);
for(const text of ['font-size:13px!important','font-size:10.8px!important','font-size:13.5px!important'])assert(layer.includes(text),'expected legible text scaling missing: '+text);
assert(!layer.includes('@import'),'Never fetch external fonts');
assert(!layer.includes('svg text')&&!layer.includes('[id^="page"]')&&!layer.includes('.form-page'),'Never touch paper / SVG / PDF typography');
assert.equal([...index.matchAll(/<link[^>]+rel="stylesheet"/g)].length,6,'No extra CSS download');
console.log('V1.0 home typography: PC/mobile legibility, stable build, no PDF modifications PASS');
