'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const css=fs.readFileSync('app/styles/aviation-reference.v1.css','utf8');
const settings=fs.readFileSync('app/modules/settings.v1.js','utf8');
const pref=fs.readFileSync('app/modules/ui-preferences.v1.js','utf8');
const controls=[...html.matchAll(/data-sags-login-theme="(light|dark)"/g)].map(x=>x[1]);
assert.deepEqual(controls,['light','dark'],'Exactly two theme choices must be visible before sign-in');
assert.ok(html.indexOf('sagsLoginThemeBar')<html.indexOf('id="personalLoginFields"'));
assert.match(html,/aria-label="Chọn giao diện"/);
const early=html.match(/<script id="sags-dual-theme-early">([\s\S]*?)<\/script>/);
assert.ok(early,'Theme control must initialize before user logs in');
const values=new Map(),els=['light','dark'].map(mode=>({mode,attrs:{'data-sags-login-theme':mode},classList:{active:false,toggle(_,on){this.active=!!on}},setAttribute(k,v){this.attrs[k]=v},getAttribute(k){return this.attrs[k]}}));
const listeners={},doc={documentElement:{theme:'',setAttribute(k,v){if(k==='data-ui-theme')this.theme=v},getAttribute(k){return k==='data-ui-theme'?this.theme:''}},querySelectorAll(){return els},addEventListener(k,fn){listeners[k]=fn}};
const wnd={addEventListener(){},dispatchEvent(){},localStorage:{getItem(k){return values.has(k)?values.get(k):null},setItem(k,v){values.set(k,v)}}};
vm.runInNewContext(early[1],{window:wnd,document:doc,localStorage:wnd.localStorage,CustomEvent:function(name,props){this.type=name;this.detail=props.detail}});
assert.equal(doc.documentElement.theme,'light');
assert.equal(typeof wnd.sagsChooseLoginTheme,'function');
assert.equal(wnd.sagsChooseLoginTheme('dark'),true);
assert.equal(doc.documentElement.theme,'dark');
assert.equal(els[1].attrs['aria-pressed'],'true');
assert.equal(els[0].attrs['aria-pressed'],'false');
assert.equal(JSON.parse(values.get('sagsUiThemeV1:loginPending')).theme,'dark');
assert.equal(wnd.sagsChooseLoginTheme('light'),true);
assert.equal(els[0].attrs['aria-pressed'],'true');
assert.equal(values.get('sagsUiThemeV1:device'),'light');
assert.equal(wnd.sagsChooseLoginTheme('invalid'),false);
assert.match(settings,/function pendingLoginTheme\(\)/);
assert.match(settings,/localStorage\.removeItem\('sagsUiThemeV1:loginPending'\)/);
assert.match(pref,/THEME_ROOT\+':loginPending'/);
assert.ok(css.includes('.sagsLoginThemeBtn.active'),'Selected theme requires a legible visual state');
for(const mode of ['light','dark'])assert.ok(css.includes('data-ui-theme="'+mode+'"] body #roleLoginModal .roleLoginCard'),'Missing login surface: '+mode);
assert.ok(css.includes('@media (max-width:480px)'),'Theme switch needs a mobile size rule');
console.log('V1.2: login theme works pre-auth, remains visible, and is handed to account Settings');
