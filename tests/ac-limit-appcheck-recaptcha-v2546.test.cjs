'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const runtime=fs.readFileSync('app/core/runtime.v503hf2.bundle.js','utf8');
const chunks=runtime.split(/\/\* SAGS_RUNTIME_CHUNK:\d+ \*\/\n/).slice(1);
assert.equal(chunks.length,5,'canonical runtime must contain five chunks');
assert.equal(chunks[1],fs.readFileSync('app/generated/runtime-2.js','utf8'),'generated multi-image importer must match canonical source');
const tools=fs.readFileSync('app/core/phases/core-tools.js','utf8');
assert.equal(tools,fs.readFileSync('app/generated/core-tools.js','utf8'),'single-image A/C LIMITS must match canonical source');
const start=runtime.indexOf('(function(root){"use strict";const BUILD="V2.2.11-AI-LIMIT-CLEANING-MULTI-IMAGE"');
const end=runtime.indexOf('})(typeof window',start);
assert(start>0&&end>start,'multi-image A/C importer found');
const importer=runtime.slice(start,end);
assert(importer.includes('async function aiSdk()'),'multi-image uses Firebase AI SDK');
assert(importer.includes('root.sagsAiLoadConfig()'),'multi-image reads AD-managed App Check key');
assert(importer.includes('const siteKey=S(cfg?.appCheckSiteKey)'),'must use AD-managed site key, not static fallback');
assert(!importer.includes('APP_CHECK_SITE_KEY_FALLBACK'),'must never quietly use an unrelated hard-coded key');
assert(importer.includes('if(!siteKey)throw Error('),'missing site key must fail with an actionable error');
assert(importer.includes('appCheckMod.getToken(check,false)'),'token is verified before AI use');
assert(importer.includes('SAGS_ACL_APP_CHECK_RECAPTCHA'),'recaptcha-error must be classified');
assert(importer.includes('e-report-sags.vercel.app'),'diagnostics point to correct production hostname');
assert(importer.includes('A/C LIMITS → AI ĐỌC ẢNH (OCR dự phòng)'),'safe review fallback is explained');
assert(importer.includes('catch(e){aiSdkPromise=null;const msg="AI đọc/gán ảnh thất bại:'),'failed import must remain unsuccessful without automatic writes');
assert(importer.includes('$(\"v2211Images\").value=\"\";renderSelectedFiles()'),'successful import resets selection');
const errorFnBegin=runtime.indexOf('function v2211AppCheckError(error)',start);
const errorFnEnd=runtime.indexOf('async function aiSdk()',errorFnBegin);
const makeError=new Function('S',runtime.slice(errorFnBegin,errorFnEnd)+';return v2211AppCheckError;')(v=>String(v??'').trim());
const ex=Object.assign(new Error('AppCheck: reCAPTCHA error'),{code:'appcheck/recaptcha-error'});
const classified=makeError(ex);
assert.equal(classified.code,'SAGS_ACL_APP_CHECK_RECAPTCHA');
assert.equal(classified.cause,ex,'diagnostic error should preserve original error');
assert.match(classified.message,/e-report-sags\.vercel\.app/);
assert.match(classified.message,/App Check/);
const noCaptcha=new Error('Ảnh không hợp lệ');
assert.equal(makeError(noCaptcha),noCaptcha,'do not relabel unrelated image errors as App Check');
const aclStart=tools.indexOf('async function readAI()'),aclEnd=tools.indexOf('function renderRows()',aclStart);
const acl=tools.slice(aclStart,aclEnd);
assert(acl.includes('window.sagsAiLoadConfig?.()'),'single-image AI should use the same admin key');
assert(!acl.includes('6LeJjYotAAAAAELyLTYPzugn_Zn37U5qOz9tHjqV'),'legacy key is not allowed in A/C reader');
assert(acl.includes('appCheckMod.getToken(appCheck,!1)'),'single-image AI verifies App Check');
assert(acl.includes('aclTryOcrFallback(file,e)'),'safe OCR fallback should remain available');
assert(acl.includes('https://www.gstatic.com/firebasejs/12.16.0/'),'both importers should use one SDK version');
console.log('A/C LIMITS App Check config, recaptcha diagnosis, no bypass, safe OCR and generated parity PASS');
